package org.streamcollab.unit;

import org.streamcollab.client.connection.ServerEndpoint;
import org.streamcollab.client.connection.TlsControlChannelFactory;

import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import javax.net.ssl.SSLException;
import javax.net.ssl.SSLServerSocket;
import javax.net.ssl.SSLSocket;
import javax.net.ssl.TrustManagerFactory;
import java.net.InetSocketAddress;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.time.Duration;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Real loopback TLS handshake test with a TEMPORARY certificate generated by
 * scripts/test-member3-stage2.sh. This test never disables server verification.
 */
public final class LocalTlsHandshakeSmokeTest {
    public static void main(String[] args) throws Exception {
        if (args.length != 2) throw new IllegalArgumentException("Usage: <p12-file> <test-password>");
        Path path = Path.of(args[0]);
        char[] password = args[1].toCharArray();
        try {
            KeyStore ks = KeyStore.getInstance("PKCS12");
            try (var file = Files.newInputStream(path)) { ks.load(file, password); }
            KeyManagerFactory kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
            kmf.init(ks, password);
            TrustManagerFactory tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
            tmf.init(ks);

            SSLContext server = SSLContext.getInstance("TLS");
            server.init(kmf.getKeyManagers(), null, null);
            SSLContext trustedClient = SSLContext.getInstance("TLS");
            trustedClient.init(null, tmf.getTrustManagers(), null);
            SSLContext untrustedClient = SSLContext.getInstance("TLS");
            untrustedClient.init(null, null, null);

            AtomicInteger accepted = new AtomicInteger();
            try (SSLServerSocket listening =
                         (SSLServerSocket) server.getServerSocketFactory().createServerSocket(0)) {
                listening.setSoTimeout(6000);
                Thread serverThread = Thread.ofVirtual().start(() -> {
                    for (int i = 0; i < 3; i++) {
                        try (SSLSocket client = (SSLSocket) listening.accept()) {
                            accepted.incrementAndGet();
                            client.setSoTimeout(3000);
                            client.startHandshake();
                        } catch (Exception ignored) {
                            // Expected failures for the two negative cases.
                        }
                    }
                });
                int port = listening.getLocalPort();
                var trusted = new TlsControlChannelFactory(trustedClient,
                        Duration.ofSeconds(3), Duration.ofSeconds(3));
                try (var channel = trusted.connect(new ServerEndpoint("localhost", port))) {
                    if (channel.input() == null || channel.output() == null) {
                        throw new AssertionError("Expected verified TLS channel");
                    }
                }
                try {
                    trusted.connect(new ServerEndpoint("127.0.0.1", port)).close();
                    throw new AssertionError("Certificate should NOT match IP address");
                } catch (SSLException expected) {
                    // The certificate has DNS:localhost SAN, not IP:127.0.0.1.
                }
                try {
                    new TlsControlChannelFactory(untrustedClient,
                            Duration.ofSeconds(3), Duration.ofSeconds(3))
                            .connect(new ServerEndpoint("localhost", port)).close();
                    throw new AssertionError("Untrusted self-signed certificate must fail");
                } catch (SSLException expected) {
                    // Trust chain validation must remain enabled.
                }
                serverThread.join(6000);
                if (accepted.get() != 3 || serverThread.isAlive()) {
                    throw new AssertionError("Expected 3 loopback TLS handshake attempts");
                }
            }
            System.out.println("PASS: 3 real TLS scenarios (trusted host / hostname mismatch / untrusted cert)");
        } finally {
            java.util.Arrays.fill(password, '\0');
        }
    }
}
